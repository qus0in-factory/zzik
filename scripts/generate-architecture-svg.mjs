// README 아키텍처 절의 Mermaid 블록을 Pele로 정적 SVG로 굽는다.
// - pele 1.13.0은 Mermaid 12.1.0의 architecture-beta를 지원한다.
// - 데스크톱은 README 블록을 그대로 쓰고, 모바일은 같은 노드/엣지에서 R/L 포트를 B/T로 바꿔 세로로 만든다.
// - 결과 SVG는 LandingPage가 ?raw로 인라인해 디자인 토큰(CSS 변수) 테마를 그대로 상속한다.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { detectType, render, supports } from 'pele'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = resolve(ROOT, 'src/ui/landing')
const readme = readFileSync(resolve(ROOT, 'README.md'), 'utf8')
const block = /```mermaid\n([\s\S]*?)```/.exec(readme)
if (block === null) throw new Error('README.md에 mermaid 블록이 없습니다')
const source = block[1].trim()
if (!supports('architecture-beta') || detectType(source) !== 'architecture') {
  throw new Error('pele이 README의 architecture-beta를 지원하지 않습니다')
}
const desktop = render(source)
// 모바일은 그룹 상자를 걷어내고 같은 노드/엣지를 위→아래로 쌓는다(390px에서 세로).
const verticalSource = source
  .replace(/^  group .*\n/gm, '')
  .replace(/ in [A-Za-z0-9_-]+$/gm, '')
  .replace(/:R --> L:/g, ':B --> T:')
const mobile = render(verticalSource)
const header = '<!-- generated by scripts/generate-architecture-svg.mjs from README.md; do not edit -->\n'
mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(resolve(OUT_DIR, 'architecture-desktop.svg'), header + desktop.svg)
writeFileSync(resolve(OUT_DIR, 'architecture-mobile.svg'), header + mobile.svg)
console.log(`architecture-desktop.svg ${desktop.width}x${desktop.height}`)
console.log(`architecture-mobile.svg ${mobile.width}x${mobile.height}`)
